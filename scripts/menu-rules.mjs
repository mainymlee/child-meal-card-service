function items(entries) {
  return entries.map(([name, price]) => ({ name, price, underBudget: price <= 10000 }));
}

export function deriveMenuProfile(name, category) {
  const matched = profiles.find(([pattern]) => pattern.test(name));
  if (matched) return { grp: matched[1], menu: items(matched[2]), menuSource: "name-derived" };
  const fallback = categoryFallback[category];
  if (fallback) return { grp: fallback[0], menu: items(fallback[1]), menuSource: "category-derived" };
  return { menu: [], menuSource: "unverified" };
}
